#!/usr/bin/env node
// scripts/generate-docs.mjs
//
// Reference documentation that cannot drift from the code, because it is produced from the code:
//
//   docs/CLI.md  from `hosterax help`            (every command, in the order the help lists them)
//   docs/API.md  from hosterax/engine/src/openapi.json and the scope table in security.mjs
//
//   node scripts/generate-docs.mjs --write   regenerate both files
//   node scripts/generate-docs.mjs --check   fail if either file is out of date (CI does this)
//
// When a command or route is added, `npm run docs:write` updates the reference; if nobody runs it,
// `npm run docs:check` (and the test suite) fails.

import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const DOCS = {
  cli: path.join(ROOT, "docs", "CLI.md"),
  api: path.join(ROOT, "docs", "API.md"),
};

const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

/** `hosterax help` as groups of [command, description]. */
export function parseHelp(text) {
  const groups = [];
  let group = null;
  let last = null;
  for (const line of text.split("\n")) {
    const header = line.match(/^ {2}(\S.*):\s*$/);
    if (header) {
      group = { title: header[1], commands: [] };
      groups.push(group);
      last = null;
      continue;
    }
    if (!group || !line.trim()) continue;
    // a command and its description are separated by two or more spaces
    const row = line.match(/^ {4}(\S.*?)(?: {2,}(\S.*))?$/);
    if (row && !/^ {12,}/.test(line)) {
      last = { command: row[1], description: row[2] || "" };
      group.commands.push(last);
    } else if (last) {
      // a wrapped line: either more of the usage or more of the description
      const more = line.trim();
      if (/^\[|^--|^\(/.test(more) && !last.description) last.command += ` ${more}`;
      else last.description = `${last.description} ${more}`.trim();
    }
  }
  return groups;
}

export function renderCliDocs(helpText) {
  const groups = parseHelp(helpText);
  const out = [
    "# Command reference",
    "",
    "<!-- Generated by scripts/generate-docs.mjs from `hosterax help`. Do not edit by hand: run `npm run docs:write`. -->",
    "",
    "`hosterax` and `htx` are the same program. `<angle brackets>` are required, `[square brackets]` optional.",
    "It talks to the engine at `http://localhost:7777` unless you `hosterax login <token> --url <engine url>`.",
    "",
  ];
  for (const g of groups) {
    out.push(`## ${g.title}`, "", "| Command | What it does |", "| --- | --- |");
    for (const c of g.commands) out.push(`| \`${cell(c.command)}\` | ${cell(c.description)} |`);
    out.push("");
  }
  return out.join("\n");
}

const SCOPE = { 1: "read", 2: "deploy", 3: "admin" };
const TITLES = {
  projects: "Projects",
  deployments: "Deployments",
  servers: "Servers",
  tunnels: "Public access (tunnels)",
  expose: "Public access",
  notifications: "Notifications",
  backups: "Backups",
  tokens: "API tokens",
  users: "Users",
  auth: "Sign-in",
  domains: "Domains",
  edge: "Edge proxy",
  email: "Email",
  docker: "Docker",
  "self-heal": "Self-healing",
  engine: "Engine (health, MCP, webhooks)",
  ai: "AI assistant",
  github: "GitHub",
  mcp: "MCP",
  orgs: "Organizations",
  jobs: "Jobs",
  "jobs-runs": "Job runs",
  previews: "PR previews",
  stats: "Statistics",
  "openapi.json": "OpenAPI document",
  apps: "App store",
  catalog: "Catalog",
};

export async function renderApiDocs() {
  const openapi = JSON.parse(
    fs.readFileSync(path.join(ROOT, "hosterax/engine/src/openapi.json"), "utf8"),
  );
  const { requiredLevel } = await import(
    pathToFileURL(path.join(ROOT, "hosterax/engine/src/security.mjs")).href
  );
  const rows = [];
  for (const [p, methods] of Object.entries(openapi.paths)) {
    const pretty = p.replace(/\{[^}]+\}/g, "{id}");
    const probe = p.replace(/\{[^}]+\}/g, "x");
    const group = p.startsWith("/api/") ? p.split("/")[2] : "engine";
    // the source does not always say which verbs a handler accepts: list such a path once, honestly
    if (Object.values(methods).some((m) => m["x-method-unspecified"])) {
      rows.push({ method: "any", path: pretty, scope: SCOPE[requiredLevel("GET", probe)], group });
      continue;
    }
    for (const method of Object.keys(methods)) {
      const level = requiredLevel(method.toUpperCase(), probe);
      rows.push({ method: method.toUpperCase(), path: pretty, scope: SCOPE[level], group });
    }
  }
  const byGroup = new Map();
  for (const r of rows) {
    if (!byGroup.has(r.group)) byGroup.set(r.group, []);
    byGroup.get(r.group).push(r);
  }
  const order = ["GET", "POST", "PUT", "PATCH", "DELETE", "any"];
  const out = [
    "# HTTP API reference",
    "",
    "<!-- Generated by scripts/generate-docs.mjs from hosterax/engine/src/openapi.json. Do not edit by hand: run `npm run docs:write`. -->",
    "",
    `The engine serves ${rows.length} routes. Send \`Authorization: Bearer <token>\`; requests from the machine the engine runs on need no token unless you changed that.`,
    "A token's scope decides what it may call: **read** (view), **deploy** (change projects, env, domains, backups), **admin** (users, tokens, servers, settings, public access).",
    "`{id}` is the project name, deployment id or similar. The machine-readable form is [`openapi.json`](../hosterax/engine/src/openapi.json).",
    "",
  ];
  for (const g of [...byGroup.keys()].sort()) {
    const list = byGroup
      .get(g)
      .sort(
        (a, b) => a.path.localeCompare(b.path) || order.indexOf(a.method) - order.indexOf(b.method),
      );
    out.push(
      `## ${TITLES[g] || g.charAt(0).toUpperCase() + g.slice(1)}`,
      "",
      "| Method | Path | Scope |",
      "| --- | --- | --- |",
    );
    for (const r of list)
      out.push(
        `| ${r.method === "any" ? "any (not stated in the source)" : r.method} | \`${r.path}\` | ${r.scope} |`,
      );
    out.push("");
  }
  return out.join("\n");
}

export function helpText() {
  const r = spawnSync(process.execPath, [path.join(ROOT, "hosterax/cli/src/cli.mjs"), "help"], {
    encoding: "utf8",
    env: { ...process.env, HOME: ROOT, USERPROFILE: ROOT, NO_COLOR: "1" },
  });
  if (r.status !== 0 || !r.stdout.includes("hosterax <command>"))
    throw new Error(`could not read \`hosterax help\`: ${r.stderr || r.stdout}`);
  return r.stdout;
}

export async function renderAll() {
  return { cli: renderCliDocs(helpText()), api: await renderApiDocs() };
}

const normalise = (s) => s.replace(/\r\n/g, "\n");

async function main() {
  const mode = process.argv.includes("--write") ? "write" : "check";
  const rendered = await renderAll();
  let stale = false;
  for (const key of Object.keys(DOCS)) {
    const file = DOCS[key];
    const want = rendered[key].replace(/\n*$/, "\n");
    if (mode === "write") {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, want);
      console.log(`wrote ${path.relative(ROOT, file)}`);
    } else if (!fs.existsSync(file) || normalise(fs.readFileSync(file, "utf8")) !== want) {
      console.error(`${path.relative(ROOT, file)} is out of date. Run: npm run docs:write`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  if (mode === "check") console.log("reference docs are up to date");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await main();
