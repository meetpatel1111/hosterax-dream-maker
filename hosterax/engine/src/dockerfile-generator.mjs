import fs from "node:fs";
import path from "node:path";

/**
 * Universal Zero-Config Dockerfile Generator for HosteraX
 * Automatically detects languages, package managers, and web frameworks,
 * generating optimized, multi-stage, high-performance Dockerfiles.
 *
 * Features:
 *  - BuildKit cache mounts for 10x faster rebuilds
 *  - HEALTHCHECK instructions for readiness probes
 *  - Multi-stage builds for minimal production images
 */

const HC = (port, startPeriod = "15s") =>
  `HEALTHCHECK --interval=10s --timeout=3s --start-period=${startPeriod} --retries=3 \\
  CMD wget -qO- http://localhost:${port}/ || exit 1`;

export function generateUniversalDockerfile(workdir) {
  const exists = (file) => fs.existsSync(path.join(workdir, file));
  const read = (file) => {
    try {
      return fs.readFileSync(path.join(workdir, file), "utf8");
    } catch {
      return "";
    }
  };

  const pkgJsonRaw = exists("package.json") ? read("package.json") : null;
  let pkg = {};
  if (pkgJsonRaw) {
    try {
      pkg = JSON.parse(pkgJsonRaw);
    } catch {}
  }
  const allDeps = { ...pkg.dependencies, ...pkg.devDependencies };
  const hasDep = (name) => !!allDeps[name];

  // ────────── 1. Bun ──────────
  if (exists("bun.lockb") || exists("bun.lock") || exists("bunfig.toml")) {
    return `# syntax=docker/dockerfile:1
# Zero-config Multi-Stage Dockerfile generated by HosteraX for Bun
FROM oven/bun:alpine AS builder
WORKDIR /app
COPY package*.json bun.lock* bunfig.toml* ./
RUN --mount=type=cache,target=/root/.bun/install/cache bun install --frozen-lockfile || bun install
COPY . .
RUN if grep -q '"build":' package.json; then bun run build || true; fi

FROM oven/bun:alpine
WORKDIR /app
COPY --from=builder /app ./
${HC(3000)}
EXPOSE 3000
CMD ["sh", "-c", "if [ -d 'dist' ] && [ -f 'dist/index.js' ]; then bun run dist/index.js; elif [ -f 'server.ts' ]; then bun run server.ts; elif [ -f 'server.js' ]; then bun run server.js; elif [ -f 'index.ts' ]; then bun run index.ts; elif [ -f 'index.js' ]; then bun run index.js; elif [ -f 'src/index.ts' ]; then bun run src/index.ts; else bun run start || bun run dev; fi"]
`;
  }

  // ────────── 2. Deno ──────────
  if (exists("deno.json") || exists("deno.jsonc") || exists("fresh.gen.ts") || (exists("main.ts") && !exists("package.json"))) {
    return `# syntax=docker/dockerfile:1
# Zero-config Dockerfile generated by HosteraX for Deno
FROM denoland/deno:alpine
WORKDIR /app
COPY . .
RUN --mount=type=cache,target=/root/.cache/deno deno cache main.ts mod.ts server.ts app.ts 2>/dev/null || true
${HC(8000)}
EXPOSE 8000
CMD ["sh", "-c", "if [ -f 'main.ts' ]; then deno run --allow-all main.ts; elif [ -f 'server.ts' ]; then deno run --allow-all server.ts; elif [ -f 'mod.ts' ]; then deno run --allow-all mod.ts; else deno run --allow-all app.ts; fi"]
`;
  }

  // ────────── 3. Next.js ──────────
  if (hasDep("next") || exists("next.config.js") || exists("next.config.mjs") || exists("next.config.ts")) {
    return `# syntax=docker/dockerfile:1
# Zero-config Multi-Stage Dockerfile generated by HosteraX for Next.js
FROM node:20-alpine AS deps
WORKDIR /app
RUN apk add --no-cache libc6-compat
COPY package*.json pnpm-lock.yaml* yarn.lock* bun.lockb* ./
RUN --mount=type=cache,target=/root/.npm \\
    --mount=type=cache,target=/root/.local/share/pnpm/store \\
    if [ -f pnpm-lock.yaml ]; then corepack enable && pnpm i --frozen-lockfile; \\
    elif [ -f yarn.lock ]; then yarn --frozen-lockfile; \\
    elif [ -f bun.lockb ]; then npm install -g bun && bun install --frozen-lockfile; \\
    else npm ci || npm install; fi

FROM node:20-alpine AS builder
WORKDIR /app
COPY --from=deps /app/node_modules ./node_modules
COPY . .
ENV NEXT_TELEMETRY_DISABLED=1
ENV NODE_ENV=production
RUN if [ -f pnpm-lock.yaml ]; then corepack enable && pnpm run build; \\
    elif [ -f yarn.lock ]; then yarn build; \\
    else npm run build; fi

FROM node:20-alpine AS runner
WORKDIR /app
ENV NODE_ENV=production
ENV NEXT_TELEMETRY_DISABLED=1
ENV PORT=3000
ENV HOSTNAME="0.0.0.0"
RUN addgroup --system --gid 1001 nodejs && adduser --system --uid 1001 nextjs
COPY --from=builder /app/public ./public 2>/dev/null || true
COPY --from=builder /app/.next ./.next
COPY --from=builder /app/node_modules ./node_modules
COPY --from=builder /app/package.json ./package.json
USER nextjs
${HC(3000, "20s")}
EXPOSE 3000
CMD ["npm", "start"]
`;
  }

  // ────────── 4. Nuxt 3 ──────────
  if (hasDep("nuxt") || exists("nuxt.config.ts") || exists("nuxt.config.js")) {
    return `# syntax=docker/dockerfile:1
# Zero-config Multi-Stage Dockerfile generated by HosteraX for Nuxt
FROM node:20-alpine AS builder
WORKDIR /app
COPY package*.json pnpm-lock.yaml* yarn.lock* ./
RUN --mount=type=cache,target=/root/.npm \\
    if [ -f pnpm-lock.yaml ]; then corepack enable && pnpm i; \\
    elif [ -f yarn.lock ]; then yarn; \\
    else npm install; fi
COPY . .
ENV NODE_ENV=production
RUN npm run build

FROM node:20-alpine AS runner
WORKDIR /app
ENV NODE_ENV=production
ENV PORT=3000
ENV HOST=0.0.0.0
COPY --from=builder /app/.output ./.output
${HC(3000)}
EXPOSE 3000
CMD ["node", ".output/server/index.mjs"]
`;
  }

  // ────────── 5. SvelteKit / Astro / Remix / SolidStart ──────────
  if (hasDep("@sveltejs/kit") || hasDep("astro") || hasDep("@remix-run/node") || hasDep("@solidjs/start")) {
    return `# syntax=docker/dockerfile:1
# Zero-config Multi-Stage Dockerfile generated by HosteraX for Modern JS Frameworks
FROM node:20-alpine AS builder
WORKDIR /app
COPY package*.json pnpm-lock.yaml* yarn.lock* ./
RUN --mount=type=cache,target=/root/.npm \\
    if [ -f pnpm-lock.yaml ]; then corepack enable && pnpm i; \\
    elif [ -f yarn.lock ]; then yarn; \\
    else npm install; fi
COPY . .
ENV NODE_ENV=production
RUN npm run build

FROM node:20-alpine AS runner
WORKDIR /app
ENV NODE_ENV=production
ENV PORT=3000
ENV HOST=0.0.0.0
RUN npm install -g serve
COPY --from=builder /app ./
${HC(3000)}
EXPOSE 3000
CMD ["sh", "-c", "if [ -d '.output/server' ]; then node .output/server/index.mjs; elif [ -d 'build' ] && [ -f 'build/index.js' ]; then node build/index.js; elif [ -f 'dist/server/entry.mjs' ]; then node dist/server/entry.mjs; elif [ -d 'dist' ]; then serve -s dist -l tcp://0.0.0.0:3000; elif [ -d 'build' ]; then serve -s build -l tcp://0.0.0.0:3000; else npm start; fi"]
`;
  }

  // ────────── 6. Generic Node.js / Express / NestJS ──────────
  if (exists("package.json")) {
    return `# syntax=docker/dockerfile:1
# Zero-config Dockerfile generated by HosteraX for Node.js
FROM node:20-alpine AS builder
WORKDIR /app
COPY package*.json pnpm-lock.yaml* yarn.lock* ./
RUN --mount=type=cache,target=/root/.npm \\
    if [ -f pnpm-lock.yaml ]; then corepack enable && pnpm i; \\
    elif [ -f yarn.lock ]; then yarn; \\
    else npm install --legacy-peer-deps || npm install; fi
COPY . .
RUN if grep -q '"build":' package.json; then npm run build || true; fi

FROM node:20-alpine
WORKDIR /app
ENV NODE_ENV=production
ENV PORT=3000
RUN npm install -g serve
COPY --from=builder /app ./
${HC(3000)}
EXPOSE 3000
CMD ["sh", "-c", "if [ -d 'dist' ] && [ -f 'dist/main.js' ]; then node dist/main.js; elif [ -d 'dist' ] && [ -f 'dist/index.js' ]; then node dist/index.js; elif [ -d 'build' ] && [ -f 'build/index.js' ]; then node build/index.js; elif [ -f 'server.js' ]; then node server.js; elif [ -f 'app.js' ]; then node app.js; elif [ -f 'index.js' ]; then node index.js; elif [ -d 'dist' ]; then serve -s dist -l tcp://0.0.0.0:3000; elif [ -d 'build' ]; then serve -s build -l tcp://0.0.0.0:3000; else npm start; fi"]
`;
  }

  // ────────── 7. Go (Golang) ──────────
  if (exists("go.mod") || exists("main.go")) {
    return `# syntax=docker/dockerfile:1
# Zero-config Multi-Stage Dockerfile generated by HosteraX for Go
FROM golang:1.23-alpine AS builder
WORKDIR /app
RUN apk --no-cache add git ca-certificates
COPY go.* ./
RUN --mount=type=cache,target=/go/pkg/mod go mod download || true
COPY . .
RUN --mount=type=cache,target=/root/.cache/go-build \\
    CGO_ENABLED=0 go build -ldflags="-s -w" -o /app/server . || CGO_ENABLED=0 go build -ldflags="-s -w" -o /app/server ./cmd/... || CGO_ENABLED=0 go build -ldflags="-s -w" -o /app/server ./...

FROM alpine:latest
WORKDIR /app
RUN apk --no-cache add ca-certificates tzdata wget
COPY --from=builder /app/server ./server
ENV PORT=8080
${HC(8080)}
EXPOSE 8080
CMD ["./server"]
`;
  }

  // ────────── 8. Rust (Cargo) ──────────
  if (exists("Cargo.toml")) {
    return `# syntax=docker/dockerfile:1
# Zero-config Multi-Stage Dockerfile generated by HosteraX for Rust
FROM rust:alpine AS builder
WORKDIR /app
RUN apk --no-cache add musl-dev
COPY . .
RUN --mount=type=cache,target=/usr/local/cargo/registry \\
    --mount=type=cache,target=/app/target \\
    cargo build --release && cp target/release/$(grep -m1 'name' Cargo.toml | sed 's/.*= *"//;s/".*//' ) /app/server 2>/dev/null || cp $(find target/release -maxdepth 1 -type f -executable | head -n 1) /app/server

FROM alpine:latest
WORKDIR /app
RUN apk --no-cache add ca-certificates tzdata wget
COPY --from=builder /app/server ./server
ENV PORT=8080
${HC(8080)}
EXPOSE 8080
CMD ["./server"]
`;
  }

  // ────────── 9. Python (FastAPI, Django, Flask, Streamlit, Poetry, uv) ──────────
  if (
    exists("requirements.txt") ||
    exists("pyproject.toml") ||
    exists("Pipfile") ||
    exists("main.py") ||
    exists("app.py") ||
    exists("manage.py")
  ) {
    const isDjango = exists("manage.py") || read("requirements.txt").includes("django");
    const isStreamlit = read("requirements.txt").includes("streamlit") || exists(".streamlit");
    const pyPort = isStreamlit ? 8501 : 8000;

    return `# syntax=docker/dockerfile:1
# Zero-config Dockerfile generated by HosteraX for Python
FROM python:3.11-slim
WORKDIR /app
ENV PYTHONUNBUFFERED=1
ENV PORT=${pyPort}

RUN apt-get update && apt-get install -y --no-install-recommends \\
    build-essential curl wget libpq-dev && rm -rf /var/lib/apt/lists/*

COPY requirements*.txt Pipfile* pyproject.toml* ./
RUN --mount=type=cache,target=/root/.cache/pip \\
    if [ -f requirements.txt ]; then pip install --no-cache-dir -r requirements.txt; \\
    elif [ -f pyproject.toml ]; then pip install --no-cache-dir poetry && poetry config virtualenvs.create false && poetry install --no-root 2>/dev/null || pip install --no-cache-dir .; \\
    fi

COPY . .
${HC(pyPort, "20s")}
EXPOSE ${pyPort}
${
  isStreamlit
    ? `CMD ["streamlit", "run", "app.py", "--server.port=${pyPort}", "--server.address=0.0.0.0"]`
    : isDjango
      ? 'CMD ["sh", "-c", "python manage.py migrate --noinput 2>/dev/null || true; if command -v gunicorn >/dev/null; then gunicorn --bind 0.0.0.0:8000 $(ls */wsgi.py | cut -d/ -f1).wsgi:application; else python manage.py runserver 0.0.0.0:8000; fi"]'
      : 'CMD ["sh", "-c", "if command -v uvicorn >/dev/null && [ -f \'main.py\' ]; then uvicorn main:app --host 0.0.0.0 --port ${PORT:-8000}; elif command -v uvicorn >/dev/null && [ -f \'app.py\' ]; then uvicorn app:app --host 0.0.0.0 --port ${PORT:-8000}; elif [ -f \'main.py\' ]; then python main.py; elif [ -f \'app.py\' ]; then python app.py; elif [ -f \'server.py\' ]; then python server.py; else python -m http.server ${PORT:-8000}; fi"]'
}
`;
  }

  // ────────── 10. Java & Kotlin (Maven / Gradle / Spring Boot) ──────────
  if (exists("pom.xml") || exists("build.gradle") || exists("build.gradle.kts") || exists("mvnw") || exists("gradlew")) {
    return `# syntax=docker/dockerfile:1
# Zero-config Multi-Stage Dockerfile generated by HosteraX for Java / Spring Boot
FROM eclipse-temurin:21-jdk-alpine AS builder
WORKDIR /app
COPY . .
RUN --mount=type=cache,target=/root/.m2 \\
    --mount=type=cache,target=/root/.gradle \\
    if [ -f gradlew ]; then chmod +x gradlew && ./gradlew bootJar --no-daemon || ./gradlew build --no-daemon; \\
    elif [ -f mvnw ]; then chmod +x mvnw && ./mvnw package -DskipTests; \\
    elif [ -f pom.xml ]; then apk add --no-cache maven && mvn package -DskipTests; \\
    else apk add --no-cache gradle && gradle build --no-daemon; fi

FROM eclipse-temurin:21-jre-alpine
WORKDIR /app
RUN apk add --no-cache wget
COPY --from=builder /app/target/*.jar /app/app.jar 2>/dev/null || COPY --from=builder /app/build/libs/*.jar /app/app.jar 2>/dev/null || true
ENV PORT=8080
${HC(8080, "30s")}
EXPOSE 8080
CMD ["sh", "-c", "exec java -Dserver.port=\${PORT:-8080} -jar $(find /app -name '*.jar' | head -n 1)"]
`;
  }

  // ────────── 11. .NET Core / C# / ASP.NET ──────────
  const filesInDir = fs.readdirSync(workdir);
  if (filesInDir.some((f) => f.endsWith(".csproj") || f.endsWith(".sln") || f.endsWith(".fsproj"))) {
    return `# syntax=docker/dockerfile:1
# Zero-config Multi-Stage Dockerfile generated by HosteraX for .NET Core
FROM mcr.microsoft.com/dotnet/sdk:8.0-alpine AS builder
WORKDIR /app
COPY . .
RUN --mount=type=cache,target=/root/.nuget/packages dotnet publish -c Release -o /app/out

FROM mcr.microsoft.com/dotnet/aspnet:8.0-alpine
WORKDIR /app
RUN apk add --no-cache wget
COPY --from=builder /app/out ./
ENV ASPNETCORE_URLS=http://+:8080
ENV PORT=8080
${HC(8080, "20s")}
EXPOSE 8080
CMD ["sh", "-c", "exec dotnet $(find . -maxdepth 1 -name '*.dll' ! -name 'Microsoft.*' ! -name 'System.*' | head -n 1)"]
`;
  }

  // ────────── 12. Ruby on Rails / Sinatra ──────────
  if (exists("Gemfile") || exists("config.ru") || exists("Rakefile")) {
    return `# syntax=docker/dockerfile:1
# Zero-config Dockerfile generated by HosteraX for Ruby on Rails
FROM ruby:3.3-alpine
WORKDIR /app
RUN apk add --no-cache build-base tzdata postgresql-dev sqlite-dev nodejs yarn wget
COPY Gemfile* ./
RUN --mount=type=cache,target=/usr/local/bundle/cache bundle install
COPY . .
RUN if [ -f bin/rails ]; then bundle exec rails assets:precompile 2>/dev/null || true; fi
ENV PORT=3000
${HC(3000, "20s")}
EXPOSE 3000
CMD ["sh", "-c", "if [ -f bin/rails ]; then bundle exec rails server -b 0.0.0.0 -p \${PORT:-3000}; elif [ -f config.ru ]; then bundle exec puma -p \${PORT:-3000}; else ruby app.rb -p \${PORT:-3000} -o 0.0.0.0; fi"]
`;
  }

  // ────────── 13. Elixir / Phoenix ──────────
  if (exists("mix.exs")) {
    return `# syntax=docker/dockerfile:1
# Zero-config Multi-Stage Dockerfile generated by HosteraX for Elixir / Phoenix
FROM hexpm/elixir:1.16-alpine AS builder
WORKDIR /app
RUN apk add --no-cache build-base git
COPY mix.* ./
RUN mix local.hex --force && mix local.rebar --force && mix deps.get --only prod
COPY . .
ENV MIX_ENV=prod
RUN mix compile && mix release

FROM alpine:latest
WORKDIR /app
RUN apk add --no-cache libstdc++ openssl ncurses-libs wget
COPY --from=builder /app/_build/prod/rel/* /app/release/
ENV PORT=4000
${HC(4000, "20s")}
EXPOSE 4000
CMD ["sh", "-c", "/app/release/bin/* start"]
`;
  }

  // ────────── 14. PHP / Laravel / Symfony / WordPress ──────────
  if (exists("composer.json") || exists("index.php") || exists("artisan")) {
    return `# syntax=docker/dockerfile:1
# Zero-config Dockerfile generated by HosteraX for PHP / Laravel
FROM php:8.3-apache
WORKDIR /var/www/html
RUN apt-get update && apt-get install -y --no-install-recommends \\
    git unzip libpq-dev libzip-dev zip wget && \\
    docker-php-ext-install pdo pdo_mysql pdo_pgsql zip && \\
    a2enmod rewrite && rm -rf /var/lib/apt/lists/*
RUN sed -ri -e 's!/var/www/html!/var/www/html/public!g' /etc/apache2/sites-available/*.conf 2>/dev/null || true
COPY . /var/www/html/
RUN --mount=type=cache,target=/root/.composer/cache \\
    if [ -f composer.json ]; then curl -sS https://getcomposer.org/installer | php -- --install-dir=/usr/local/bin --filename=composer && composer install --no-dev --optimize-autoloader; fi
RUN chown -R www-data:www-data /var/www/html
${HC(80)}
EXPOSE 80
`;
  }

  // ────────── 15. Fallback Static Web Server (SPA Fallback + Gzip) ──────────
  return `# Fallback static Dockerfile generated by HosteraX
FROM nginx:alpine
RUN rm -rf /etc/nginx/conf.d/*
RUN echo 'server { \\
    listen 80; \\
    location / { \\
        root /usr/share/nginx/html; \\
        index index.html index.htm; \\
        try_files $uri $uri/ /index.html; \\
    } \\
}' > /etc/nginx/conf.d/default.conf
COPY . /usr/share/nginx/html
HEALTHCHECK --interval=10s --timeout=3s --start-period=5s --retries=3 \\
  CMD wget -qO- http://localhost:80/ || exit 1
EXPOSE 80
`;
}
